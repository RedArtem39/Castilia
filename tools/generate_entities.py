"""Generate the semicolon-terminated HTML named-entity table for no_std Rust."""

from html.entities import html5
from pathlib import Path
import unicodedata


ROOT = Path(__file__).resolve().parents[1]
entries = sorted((name[:-1], value) for name, value in html5.items() if name.endswith(";"))


def rust_string(value: str) -> str:
    parts = ['"']
    for character in value:
        if character == '"':
            parts.append('\\"')
        elif character == "\\":
            parts.append("\\\\")
        elif character == "\n":
            parts.append("\\n")
        elif character == "\t":
            parts.append("\\t")
        elif unicodedata.category(character) in {"Cc", "Cf"} or character == "\u00ad":
            parts.append(f"\\u{{{ord(character):X}}}")
        else:
            parts.append(character)
    parts.append('"')
    return "".join(parts)


lines = [
    "// Generated by tools/generate_entities.py from Python's HTML5 entity table.",
    "pub static NAMED: &[(&str, &str)] = &[",
]
for name, value in entries:
    lines.append(f"    ({rust_string(name)}, {rust_string(value)}),")
lines.append("];")
lines.append("")
(ROOT / "src" / "entities.rs").write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {len(entries)} named entities")
